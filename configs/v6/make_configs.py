"""Generate the step-2I configs (v6) from the 2H / benchmark configs.

    python configs/v6/make_configs.py

Changes against 2H.5 / the benchmarks (see docs/PLAN_REALISM.md, step 2I):
  - noise-free detectors everywhere (no sensor noise, no detector dropout);
  - workers: SMDP discounting (0.995 per s), 150 m approach detector, a residual head that
    starts as the expert (agent.ref_action = 0, AGREE) with little exploration, validation on
    2 scenarios per level; a worker for max-pressure on the corridor too;
  - a stage-control RL expert per network (rl: per-junction DQN as the benchmarks' rl2;
    rlf: one phase-wise FRAP-style network for all junctions), selectable by the table;
  - benchmarks: rl2 and the phase-wise variant without detector noise.
"""

import copy
import os
import tomllib

import tomli_w

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'configs', 'v6')
HEADER = '# Generated by configs/v6/make_configs.py (step 2I); edit that script, not this file.\n'

NETWORKS = {
    'corridor': {
        'worker_tpl': 'configs/hierarchy/workers/corridor_greenwave.toml',
        'workers': {'greenwave': 0, 'coord_actuated': 1, 'maxpressure': 2},
        'table_scenarios': 8,
    },
    'maribor': {
        'worker_tpl': 'configs/hierarchy/workers/maribor_maxpressure.toml',
        'workers': {'maxpressure': 2, 'actuated': 3},
        'table_scenarios': 6,
    },
}
EXPERTS = ['greenwave', 'coord_actuated', 'maxpressure', 'actuated', 'rl', 'rlf']
BENCHMARKS = ['cologne1', 'cologne3', 'cologne8', 'ingolstadt1', 'ingolstadt7', 'ingolstadt21',
              'grid4x4', 'arterial4x4']
NOISE_FREE = {'noise': 0.0, 'dropout': 0.0}


def load(path):
    with open(os.path.join(ROOT, path), 'rb') as f:
        return tomllib.load(f)


def write(rel, data, comment):
    path = os.path.join(OUT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(HEADER + ''.join(f'# {line}\n' for line in comment.splitlines()))
        f.write(tomli_w.dumps(data))
    return path


def worker(net, expert, index):
    d = load(NETWORKS[net]['worker_tpl'])
    d['name'] = f'v6_wk_{net}_{expert}'
    d['workers'] = 1
    d['hierarchy']['fixed_expert'] = index
    d['signals']['experts'] = EXPERTS       # same input size as the tables (rl, rlf unused)
    d['observation'].update(NOISE_FREE, approach_length=150.0)
    d['reward']['scale'] = 0.1          # SMDP sums the seconds: keeps Q near the 2H.5 scale
    d['agent'] = {'shared': True, 'smdp': True, 'gamma': 0.995, 'ref_action': 0}
    d['train'].update(episodes=150, eps_start=0.2, eps_min=0.02, eps_fraction=0.5,
                      val_every=25, val_per_level=2)
    return write(f'workers/{net}_{expert}.toml', d,
                 f'Worker for the {expert} expert on {net}: starts as the expert (AGREE), SMDP,\n'
                 f'approach detector, noise-free.\n'
                 f'  tsc train configs/v6/workers/{net}_{expert}.toml --seeds 0-2')


def rl_expert(net, phase):
    d = load(NETWORKS[net]['worker_tpl'])
    name = f'v6_{net}_{"rlf" if phase else "rl"}'
    d['name'] = name
    d['workers'] = 1
    d['signals'] = {'control': 'stages', 'decision_interval': 5}
    d.pop('hierarchy')
    d['observation'] = {'mode': 'detector', 'comm': False, 'approach_length': 150.0, **NOISE_FREE}
    d['reward'] = {'kind': 'queue'}
    d['agent'] = {'smdp': True, 'gamma': 0.995}
    if phase:
        d['observation']['layout'] = 'phase'
        d['agent'].update(phase_net=True, hidden=[64, 64], buffer_size=100000)
    d['train'] = {k: v for k, v in d['train'].items() if k not in ('plan_levels', 'plan_match')}
    d['train'].update(episodes=150, val_every=15, val_per_level=2)
    kind = 'one phase-wise network (FRAP-style) for all junctions' if phase else \
        'one DQN per junction (as the benchmarks\' rl2)'
    return write(f'rl/{net}_{"rlf" if phase else "rl"}.toml', d,
                 f'Stage-control RL on {net}, {kind}: detector state + approach detector,\n'
                 f'SMDP, queue reward, noise-free, no shield. Also the hierarchy\'s rl expert.\n'
                 f'  tsc train configs/v6/rl/{net}_{"rlf" if phase else "rl"}.toml --seeds 0-2')


def table(net):
    """Lookup-table hierarchy over the classic experts and both RL experts, each classic one
    with its v6 worker where that passed acceptance."""
    d = load(NETWORKS[net]['worker_tpl'])
    d['name'] = f'v6_{net}_table'
    d['workers'] = 4
    d['signals']['experts'] = EXPERTS
    d['signals']['rl_experts'] = {k: f'outputs/train/v6_{net}_{k}/s{{seed}}' for k in ('rl', 'rlf')}
    d['hierarchy'] = {
        'scope': 'network', 'interval': 300, 'worker': 'expert', 'manager': 'table',
        'table_scenarios': NETWORKS[net]['table_scenarios'], 'hysteresis': 2,
        'table_alone': True,
        'worker_runs': {e: f'outputs/train/v6_wk_{net}_{e}/s{{seed}}'
                        for e in NETWORKS[net]['workers']},
    }
    d['observation'].update(NOISE_FREE, approach_length=150.0)
    d['agent'] = {'shared': True, 'smdp': True, 'gamma': 0.995, 'ref_action': 0}
    return write(f'tables/{net}_table.toml', d,
                 f'Lookup-table hierarchy on {net}: experts {EXPERTS}, the classic ones with\n'
                 f'their v6 worker where one passed acceptance; per level the table picks the\n'
                 f'expert and whether its worker acts. Nothing is trained.\n'
                 f'  tsc train configs/v6/tables/{net}_table.toml --seeds 0-2')


def table_candidates(net, experts):
    """As table(), but these experts' workers enter the table even if they failed the
    acceptance test (copies under v6c_wk_*, see admit_candidates.py): the table measures
    each with and without its worker per level and picks."""
    path = table(net)
    with open(path, 'rb') as f:
        d = tomllib.load(f)
    d['name'] = f'v6_{net}_tablew'
    for e in experts:
        d['hierarchy']['worker_runs'][e] = f'outputs/train/v6c_wk_{net}_{e}/s{{seed}}'
    return write(f'tables/{net}_tablew.toml', d,
                 f'Lookup-table hierarchy on {net} as {net}_table.toml, but the {", ".join(experts)}\n'
                 f'worker(s) enter as candidates although they failed acceptance (lower delay,\n'
                 f'not significant on 12 scenarios); the table decides per level.\n'
                 f'  tsc train configs/v6/tables/{net}_tablew.toml --seeds 0-2')


def evaluation(net, opposite=False):
    src = {'corridor': 'configs/hierarchy/evaluate_corridor.toml',
           'maribor': 'configs/hierarchy/evaluate_maribor.toml'}[net]
    d = load(src)
    d['name'] = f'v6_{net}' + ('_opposite' if opposite else '')
    d['workers'] = 14
    d['observation'] = {'mode': 'detector', **NOISE_FREE}
    d['evaluate']['runs'] = [f'outputs/train/v6_{net}_table*/s*', f'outputs/train/v6_{net}_rl*/s*']
    if opposite:
        d['evaluate']['plan_direction'] = 'opposite'
    return write(f'eval/{net}{"_opposite" if opposite else ""}.toml', d,
                 f'Step 2I: v6 tables and RL experts on {net} vs the noise-free baselines'
                 f'{" (opposite-direction plans)" if opposite else ""}.\n'
                 f'  tsc evaluate configs/v6/eval/{net}{"_opposite" if opposite else ""}.toml')


def bench(name, phase):
    d = load(f'configs/benchmarks/rl_improved/{name}.toml')
    d['name'] = f'{"rl2f" if phase else "rl2nf"}_{name}'
    d['workers'] = 1
    d['observation'].update(NOISE_FREE)
    if phase:
        d['observation']['layout'] = 'phase'
        d['agent'].update(phase_net=True, hidden=[64, 64], buffer_size=100000)
    kind = 'phase-wise FRAP-style network shared by all junctions' if phase else 'rl2'
    return write(f'bench/{"rl2f" if phase else "rl2nf"}_{name}.toml', d,
                 f'Benchmark {name}: {kind} without detector noise / dropout.\n'
                 f'  tsc train configs/v6/bench/{"rl2f" if phase else "rl2nf"}_{name}.toml --seeds 0-4')


def main():
    made = []
    for net, spec in NETWORKS.items():
        for expert, index in spec['workers'].items():
            made.append(worker(net, expert, index))
        for phase in (False, True):
            made.append(rl_expert(net, phase))
        made.append(table(net))
        if net == 'maribor':
            made.append(table_candidates(net, ['maxpressure']))
        made.append(evaluation(net))
    made.append(evaluation('corridor', opposite=True))
    for name in BENCHMARKS:
        made.append(bench(name, False))
        made.append(bench(name, True))
    for p in made:
        print(os.path.relpath(p, ROOT))


if __name__ == '__main__':
    main()
